os.environ.setdefault("MPLCONFIGDIR", "/tmp/matplotlib")

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns

LOGGER = logging.getLogger(__name__)
STRATEGY_ORDER = ["random", "pop", "bpr", "hybrid", "budget", "history", "ensemble"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot scenario-1 constrained recommendation results.")
    parser.add_argument(
        "--metrics_json",
        default="results/scenario1_metrics_recall_suite.json",
        help="Metrics JSON generated by run_scenario1_baselines.py.",
    )
    parser.add_argument("--output_dir", default="results/figures", help="Directory to save figures.")
    parser.add_argument("--format", default="png", choices=["png", "pdf"], help="Figure format.")
    parser.add_argument("--dpi", type=int, default=300, help="Output resolution for raster formats.")
    return parser.parse_args()


def load_metrics(metrics_json: str) -> Tuple[Dict[str, Any], pd.DataFrame, pd.DataFrame]:
    path = Path(metrics_json)
    if not path.exists():
        raise FileNotFoundError(f"Metrics JSON not found: {path}")
    with path.open("r", encoding="utf-8") as f:
        payload = json.load(f)

    summary = payload.get("summary", {})
    summaries_by_strategy = payload.get("summaries_by_strategy", {})
    records = payload.get("records", [])
    if not summary:
        raise ValueError("Metrics JSON missing non-empty 'summary'.")
    if not records:
        raise ValueError("Metrics JSON missing non-empty 'records'.")

    if summaries_by_strategy:
        rows = []
        for strategy, strategy_summary in summaries_by_strategy.items():
            row = dict(strategy_summary)
            row["strategy"] = strategy
            rows.append(row)
        summary_df = pd.DataFrame(rows)
    else:
        row = dict(summary)
        row["strategy"] = row.get("recall_strategy", "strategy")
        summary_df = pd.DataFrame([row])

    records_df = pd.DataFrame(records)
    if "strategy" not in records_df.columns:
        records_df["strategy"] = summary.get("recall_strategy", "strategy")
    summary_df["strategy"] = pd.Categorical(summary_df["strategy"], categories=STRATEGY_ORDER, ordered=True)
    summary_df = summary_df.sort_values("strategy").reset_index(drop=True)
    records_df["strategy"] = pd.Categorical(records_df["strategy"], categories=STRATEGY_ORDER, ordered=True)
    return summary, summary_df, records_df


def setup_style() -> None:
    sns.set_theme(
        context="paper",
        style="whitegrid",
        font_scale=1.05,
        rc={
            "figure.dpi": 120,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.titleweight": "bold",
            "axes.labelsize": 10,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "legend.fontsize": 8,
        },
    )


def save_figure(fig: plt.Figure, output_dir: Path, stem: str, fmt: str, dpi: int) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"{stem}.{fmt}"
    fig.tight_layout()
    fig.savefig(path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    LOGGER.info("Saved figure: %s", path)
    return path


def _to_numeric(df: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    out = df.copy()
    for col in columns:
        if col in out.columns:
            out[col] = pd.to_numeric(out[col], errors="coerce")
    return out


def plot_recall_accuracy_comparison(summary_df: pd.DataFrame, output_dir: Path, fmt: str, dpi: int) -> Path:
    required = ["recall_hit_at_k", "raw_top10_hit_at_10", "final_hit_at_10", "final_ndcg_at_10"]
    missing = [col for col in required if col not in summary_df.columns]
    if missing:
        raise ValueError(f"Summary missing keys required for accuracy plot: {missing}")

    plot_df = _to_numeric(summary_df, required).melt(
        id_vars="strategy",
        value_vars=required,
        var_name="Metric",
        value_name="Score",
    )
    names = {
        "recall_hit_at_k": "Recall HR@K",
        "raw_top10_hit_at_10": "Raw HR@10",
        "final_hit_at_10": "Agent HR@10",
        "final_ndcg_at_10": "Agent NDCG@10",
    }
    plot_df["Metric"] = plot_df["Metric"].map(names)

    fig, ax = plt.subplots(figsize=(8.0, 4.2))
    sns.barplot(data=plot_df, x="strategy", y="Score", hue="Metric", ax=ax)
    ax.set_title("Recall Strategy Accuracy Comparison")
    ax.set_xlabel("Recall strategy")
    ax.set_ylabel("Rate / NDCG")
    ax.set_ylim(0, max(0.05, float(plot_df["Score"].max()) * 1.25 if plot_df["Score"].notna().any() else 0.05))
    ax.legend(title="", loc="upper left", frameon=True)
    ax.tick_params(axis="x", rotation=25)
    return save_figure(fig, output_dir, "scenario1_recall_accuracy_comparison", fmt, dpi)


def plot_constraint_by_strategy(summary_df: pd.DataFrame, output_dir: Path, fmt: str, dpi: int) -> Path:
    required = [
        "raw_top10_fully_repaired",
        "fully_repaired",
        "raw_top10_inventory_safety_rate",
        "agent_inventory_safety_rate",
    ]
    missing = [col for col in required if col not in summary_df.columns]
    if missing:
        raise ValueError(f"Summary missing keys required for constraint plot: {missing}")

    rows = []
    for _, row in _to_numeric(summary_df, required).iterrows():
        strategy = row["strategy"]
        rows.extend(
            [
                {"strategy": strategy, "Metric": "CSR", "Layer": "Raw Top-10", "Score": row["raw_top10_fully_repaired"]},
                {"strategy": strategy, "Metric": "CSR", "Layer": "Agent Top-10", "Score": row["fully_repaired"]},
                {"strategy": strategy, "Metric": "Inventory", "Layer": "Raw Top-10", "Score": row["raw_top10_inventory_safety_rate"]},
                {"strategy": strategy, "Metric": "Inventory", "Layer": "Agent Top-10", "Score": row["agent_inventory_safety_rate"]},
            ]
        )
    plot_df = pd.DataFrame(rows)

    fig, axes = plt.subplots(1, 2, figsize=(9.2, 3.8), sharey=True)
    palette = {"Raw Top-10": "#A9B4C2", "Agent Top-10": "#1F6F8B"}
    for ax, metric in zip(axes, ["CSR", "Inventory"]):
        sub = plot_df[plot_df["Metric"] == metric]
        sns.barplot(data=sub, x="strategy", y="Score", hue="Layer", palette=palette, ax=ax)
        ax.set_title(metric)
        ax.set_xlabel("")
        ax.set_ylabel("Rate" if metric == "CSR" else "")
        ax.set_ylim(0, 1.08)
        ax.tick_params(axis="x", rotation=25)
        ax.legend(title="", loc="lower right", frameon=True)
    fig.suptitle("Constraint Compliance by Recall Strategy", y=1.03, fontweight="bold")
    return save_figure(fig, output_dir, "scenario1_constraint_by_strategy", fmt, dpi)


